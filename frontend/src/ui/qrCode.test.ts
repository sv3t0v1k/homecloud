describe('createQrMatrix', () => {
  it('совпадает с эталонной матрицей для короткой строки (v1)', () => {
    const matrix = createQrMatrix('HELLO')
    expect(matrix.size).toBe(21)
    expect(matrix.modules.map((row) => row.map((cell) => (cell ? '1' : '0')).join(''))).toEqual(HELLO_V1)
  })

  it('совпадает с эталонной матрицей для URL (v3)', () => {
    const matrix = createQrMatrix('https://homecloud.local/s/AbCdEf0123456789')
    expect(matrix.size).toBe(29)
    expect(matrix.modules.map((row) => row.map((cell) => (cell ? '1' : '0')).join(''))).toEqual(URL_V3)
  })

  it('выбирает версию по длине и отклоняет слишком длинный текст', () => {
    expect(createQrMatrix('a'.repeat(50)).size).toBeGreaterThan(21)
    expect(() => createQrMatrix('a'.repeat(500))).toThrow(/слишком длинный/)
  })

  it('рисует finder-паттерны по углам', () => {
    const { modules, size } = createQrMatrix('test')
    for (const [row, col] of [[0, 0], [0, size - 7], [size - 7, 0]]) {
      for (let r = 0; r < 7; r += 1) {
        for (let c = 0; c < 7; c += 1) {
          const expected = r === 0 || r === 6 || c === 0 || c === 6 || (r >= 2 && r <= 4 && c >= 2 && c <= 4)
          expect(modules[row + r][col + c]).toBe(expected)
        }
      }
    }
  })
})
